# ============================================================
# FOURIER FEATURE GENERATION
# ============================================================

def create_fourier_terms(index, period=365.25, K=5):
    """
    Generate Fourier terms for annual seasonality.

    Parameters
    ----------
    index : pandas DatetimeIndex
        Historical or future dates.

    period : float
        Annual seasonal period.

    K : int
        Number of Fourier harmonics.

    Returns
    -------
    pandas.DataFrame
        Fourier sine and cosine features.
    """

    t = np.arange(len(index))

    fourier = pd.DataFrame(index=index)

    for k in range(1, K + 1):

        fourier[f"sin_{k}"] = np.sin(
            2 * np.pi * k * t / period
        )

        fourier[f"cos_{k}"] = np.cos(
            2 * np.pi * k * t / period
        )

    return fourier


