# LOAD AND PREPARE DATA
# ============================================================

@st.cache_data
def load_temperature_data(file_path):

    if not Path(file_path).exists():
        raise FileNotFoundError(
            f"Dataset not found: {file_path}. "
            "Please upload daily_minimum_temperature_cleaned.csv "
            "to the GitHub repository root."
        )

    df = pd.read_csv(file_path)

    # Support the CSV format generated by your notebook.
    if "Date" in df.columns:

        df["Date"] = pd.to_datetime(
            df["Date"],
            errors="coerce"
        )

        df = df.set_index("Date")

    else:
        # Also support a CSV where Date was saved as the index.
        first_column = df.columns[0]

        parsed_dates = pd.to_datetime(
            df[first_column],
            errors="coerce"
        )

        if parsed_dates.notna().all():

            df[first_column] = parsed_dates

            df = df.set_index(first_column)

        else:

            raise ValueError(
                "Could not identify the Date column in the dataset."
            )

    if "Temperature" not in df.columns:
        raise ValueError(
            "The dataset must contain a 'Temperature' column."
        )

    df = df[["Temperature"]].copy()

    df["Temperature"] = pd.to_numeric(
        df["Temperature"],
        errors="coerce"
    )

    df = df.dropna(subset=["Temperature"])

    df = df.sort_index()

    # Ensure one observation per date.
    df = df[
        ~df.index.duplicated(keep="last")
    ]

    if len(df) < 365:
        raise ValueError(
            "The dataset contains fewer than 365 valid "
            "temperature observations."
        )

    # Your notebook uses daily observations.
    # Reject gaps rather than silently creating misleading
    # Fourier time steps.
    expected_index = pd.date_range(
        start=df.index.min(),
        end=df.index.max(),
        freq="D"
    )

    if not df.index.equals(expected_index):

        raise ValueError(
            "The dataset must contain continuous daily observations. "
            "Please check for missing dates before forecasting."
        )

    df.index.name = "Date"

    return df


# ============================================================
# TRAIN MODEL AND GENERATE FORECAST
# ============================================================

@st.cache_resource(show_spinner=False)
def fit_temperature_model(data_path, data_modified_time):

    # Load the cleaned historical observations.
    df = load_temperature_data(data_path)

    temperature = df["Temperature"].astype(float)

    # --------------------------------------------------------
    # Historical Fourier features
    # --------------------------------------------------------

    X_historical = create_fourier_terms(
        temperature.index,
        period=365.25,
        K=5
    )

    # --------------------------------------------------------
    # Fit final SARIMAX model
    # --------------------------------------------------------

    model = SARIMAX(
        temperature,
        exog=X_historical,
        order=(3, 0, 1),
        seasonal_order=(0, 0, 0, 0),
        enforce_stationarity=False,
        enforce_invertibility=False
    )

    fitted_model = model.fit(
        disp=False
    )

    return df, fitted_model


def generate_forecast(df, fitted_model, forecast_days=365):

    temperature = df["Temperature"]

    # --------------------------------------------------------
    # Create future dates
    # --------------------------------------------------------

    future_index = pd.date_range(
        start=temperature.index.max()
        + pd.Timedelta(days=1),
        periods=forecast_days,
        freq="D"
    )

    # --------------------------------------------------------
    # Generate future Fourier features
    #
    # IMPORTANT:
    # The Fourier time index must continue from the historical
    # series. Do not restart t at zero for the forecast period.
    # --------------------------------------------------------

    combined_index = temperature.index.append(
        future_index
    )

    fourier_all = create_fourier_terms(
        combined_index,
        period=365.25,
        K=5
    )

    X_future = fourier_all.loc[
        future_index
    ]

    # --------------------------------------------------------
    # Generate forecasts and prediction intervals
    # --------------------------------------------------------

    forecast_result = fitted_model.get_forecast(
        steps=forecast_days,
        exog=X_future
    )

    forecast_mean = forecast_result.predicted_mean

    confidence_intervals = forecast_result.conf_int(
        alpha=0.05
    )

    # --------------------------------------------------------
    # Create results DataFrame
    # --------------------------------------------------------

    forecast_df = pd.DataFrame(
        {
            "Date": future_index,
            "Forecast_Temperature": forecast_mean.to_numpy(),
            "Lower_95_CI": confidence_intervals.iloc[:, 0].to_numpy(),
            "Upper_95_CI": confidence_intervals.iloc[:, 1].to_numpy()
        }
    )

    forecast_df["Month"] = (
        forecast_df["Date"].dt.month_name()
    )

    forecast_df["Interval_Width"] = (
        forecast_df["Upper_95_CI"]
        - forecast_df["Lower_95_CI"]
    )

    return forecast_df


